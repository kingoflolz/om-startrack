/* Shared STAR capture framing and outcomes. */
#ifndef OLYMPUS_STAR_GATT_SERVICE_PROTOCOL_H
#define OLYMPUS_STAR_GATT_SERVICE_PROTOCOL_H



#include <stdint.h>


#define STAR_GATT_COMMAND_CAPTURE_RECIPE UINT8_C(0x01)
#define STAR_GATT_VALUE_PEAKS UINT8_C(0x81)
#define STAR_GATT_VALUE_DONE UINT8_C(0x82)

enum star_gatt_capture_outcome {
    STAR_GATT_CAPTURE_OK = 0x00,
    STAR_GATT_CAPTURE_REJECTED_NO_MUTATION = 0x01,
    STAR_GATT_CAPTURE_FAILED_SAFE = 0x02,
    STAR_GATT_CAPTURE_FAILED_UNSAFE = 0x03
};

#define STAR_GATT_CAPTURE_REQUEST_SIZE 1u
#define STAR_GATT_DONE_FAILURE_SIZE 4u
#define STAR_GATT_DONE_PREFIX_SIZE 4u

#define STAR_GATT_SETTING_COUNT 3u
#define STAR_GATT_SETTING_LABEL_MAX 31u
#define STAR_GATT_CATALOG_COUNT_MIN 1u
#define STAR_GATT_CATALOG_COUNT_MAX 128u
#define STAR_GATT_CATALOG_MIN_SIZE 3u
#define STAR_GATT_CATALOG_MAX_SIZE 512u
#define STAR_GATT_SETTINGS_WRITE_MIN_SIZE 6u
#define STAR_GATT_SETTINGS_WRITE_MAX_SIZE                              \
    (STAR_GATT_SETTING_COUNT * (1u + STAR_GATT_SETTING_LABEL_MAX))
#define STAR_GATT_RECIPE_MIN_SIZE STAR_GATT_SETTINGS_WRITE_MIN_SIZE
#define STAR_GATT_RECIPE_MAX_SIZE STAR_GATT_SETTINGS_WRITE_MAX_SIZE
#define STAR_GATT_LENS_NAME_MAX 32u
#define STAR_GATT_MAX_PEAKS 256u
#define STAR_GATT_PEAK_WIRE_SIZE 8u
#define STAR_GATT_PEAKS_PREFIX_SIZE 1u
#define STAR_GATT_PEAKS_MAX_PER_VALUE 63u


#define STAR_GATT_APERTURE_BOUND_COUNT 2u
#define STAR_GATT_STATE_LABEL_COUNT                                  \
    (STAR_GATT_SETTING_COUNT + STAR_GATT_APERTURE_BOUND_COUNT)
#define STAR_GATT_STATE_FIXED_SIZE 16u
#define STAR_GATT_STATE_MIN_SIZE                                     \
    (STAR_GATT_STATE_FIXED_SIZE + STAR_GATT_STATE_LABEL_COUNT)
#define STAR_GATT_STATE_MAX_SIZE                                      \
    (STAR_GATT_STATE_FIXED_SIZE +                                    \
     STAR_GATT_STATE_LABEL_COUNT * STAR_GATT_SETTING_LABEL_MAX +     \
     STAR_GATT_LENS_NAME_MAX)




#define STAR_GATT_DONE_OK_FIXED_SIZE 15u
#define STAR_GATT_DONE_OK_MAX_SIZE                                  \
    (STAR_GATT_DONE_OK_FIXED_SIZE + STAR_GATT_LENS_NAME_MAX)


#define STAR_GATT_DEFAULT_ATT_MTU 23u
#define STAR_GATT_ATT_VALUE_OVERHEAD 3u
#define STAR_GATT_ATT_ATTRIBUTE_VALUE_MAX 512u
#define STAR_GATT_CAPTURE_MIN_ATT_MTU                                \
    (STAR_GATT_DONE_OK_MAX_SIZE + STAR_GATT_ATT_VALUE_OVERHEAD)

#define STAR_GATT_Y_WIDTH 1296u
#define STAR_GATT_Y_HEIGHT 972u

#endif
